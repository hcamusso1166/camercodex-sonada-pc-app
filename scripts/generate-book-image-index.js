#!/usr/bin/env node
const fs = require("node:fs");
const path = require("node:path");

const repoRoot = path.resolve(__dirname, "..");
const booksRoot = path.join(repoRoot, "books");
const outputPath = path.join(booksRoot, "image-index.js");
const index = {};

for (const bookDirent of fs.readdirSync(booksRoot, { withFileTypes: true })) {
  if (!bookDirent.isDirectory()) continue;
  const pagesDir = path.join(booksRoot, bookDirent.name, "pages");
  if (!fs.existsSync(pagesDir)) {
    index[bookDirent.name] = [];
    console.log(`[IMAGE-INDEX] book=${bookDirent.name} pagesScanned=0 imagesFound=0`);
    continue;
  }

  const pageFiles = fs.readdirSync(pagesDir).filter(file => file.endsWith(".json")).sort();
  const entries = [];
  const seen = new Set();
  for (const file of pageFiles) {
    const filePath = path.join(pagesDir, file);
    const pageData = JSON.parse(fs.readFileSync(filePath, "utf8"));
    if (!Number.isInteger(pageData.page) || !pageData.bookId) {
      throw new Error(`[IMAGE-INDEX] missing/invalid page or bookId in ${path.relative(repoRoot, filePath)}`);
    }
    if (pageData.bookId !== bookDirent.name) {
      throw new Error(`[IMAGE-INDEX] bookId mismatch in ${path.relative(repoRoot, filePath)}`);
    }
    if (pageData.images !== undefined && !Array.isArray(pageData.images)) {
      throw new Error(`[IMAGE-INDEX] images must be an array in ${path.relative(repoRoot, filePath)}`);
    }
    for (const image of pageData.images || []) {
      const imageId = typeof image?.imageId === "string" ? image.imageId.trim() : "";
      if (!imageId) {
        throw new Error(`[IMAGE-INDEX] missing imageId in ${path.relative(repoRoot, filePath)}`);
      }
      const key = `${pageData.bookId}:${pageData.page}:${imageId}`;
      if (seen.has(key)) throw new Error(`[IMAGE-INDEX] duplicate ${key}`);
      seen.add(key);
      entries.push({
        bookId: pageData.bookId,
        page: pageData.page,
        imageId,
        description: typeof image.description === "string" ? image.description.trim() : "",
        audio: `${pageData.bookId}/audios/page-${String(pageData.page).padStart(3, "0")}/images/${imageId}_p1.mp3`,
      });
    }
  }
  entries.sort((a, b) => a.page - b.page || a.imageId.localeCompare(b.imageId));
  index[bookDirent.name] = entries;
  console.log(`[IMAGE-INDEX] book=${bookDirent.name} pagesScanned=${pageFiles.length} imagesFound=${entries.length}`);
}

const contents = `/* Generated by scripts/generate-book-image-index.js. Do not edit. */\n` +
  `(function (global) {\n  global.BOOK_IMAGE_INDEX = Object.freeze(${JSON.stringify(index, null, 2)});\n` +
  `  if (typeof module !== "undefined" && module.exports) module.exports = global.BOOK_IMAGE_INDEX;\n` +
  `})(typeof window !== "undefined" ? window : globalThis);\n`;
fs.writeFileSync(outputPath, contents);
console.log(`[IMAGE-INDEX] output=${path.relative(repoRoot, outputPath)}`);